def donut(cv, cx, cy, r, pct, c_fill, c_rest, c_bg=None):
    # full ring in c_fill, tiny remainder wedge in c_rest, paper centre
    import math
    cv.circle(cx, cy, r, c_fill)
    rem = 100.0 - pct
    if rem > 0.05:
        a0 = -math.pi / 2
        a1 = a0 + 2 * math.pi * (rem / 100.0)
        pts = [(cx, cy)]
        n = 24
        for i in range(n + 1):
            a = a0 + (a1 - a0) * i / n
            pts.append((cx + int(r * math.cos(a)), cy + int(r * math.sin(a))))
        cv.poly(pts, c_rest)
    cv.circle(cx, cy, int(r * 0.62), PAPER)

