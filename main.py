# ------------------------------------------------------------- text engine --
# Glyphs are rendered with 3x supersampling: each output pixel samples a 3x3
# grid of points against the bitmap, so edges are smooth, not jagged.
_MASK_CACHE = {}

def _glyph_advance(ch):
    rows = FONT.get(ch, FONT['?'])
    w = 0
    for r in rows:
        w = max(w, len(r.rstrip('.')))
    if ch == ' ':
        return 4
    return max(3, w + 1)

def _xscale(ch):
    """Horizontal squeeze for wide lowercase (grid is 12 wide but x-height
    is only 10 rows, so lowercase would otherwise render ~1.5x too wide)."""
    if ch.islower() and ch not in 'ijl':
        return 0.75
    return 1.0

def _advance_px(ch, size):
    return _glyph_advance(ch) * (size / 16.0) * _xscale(ch)

def _glyph_mask(ch, size, italic=False, hsqueeze=1.0):
    """Coverage mask (bytes 0..9) for one glyph at pixel height `size`."""
    key = (ch, size, italic, hsqueeze)
    m = _MASK_CACHE.get(key)
    if m is not None:
        return m
    rows = FONT.get(ch, FONT['?'])
    cell = size / 16.0
    cell_x = cell * _xscale(ch) * hsqueeze
    ncols = max(len(r) for r in rows)
    pw = int(ncols * cell_x + 0.999) + 2
    if italic:
        pw += int(3 * cell) + 2  # room for the shear shift at the top
    ph = int(16 * cell + 0.999) + 2
    shear = 0.18 if italic else 0.0
    baseline = 14.0 * cell
    mask = bytearray(pw * ph)
    for py in range(ph):
        for px in range(pw):
            cov = 0
            for sy in range(3):
                y = py + (sy + 0.5) / 3.0
                row = int(y / cell)
                if row < 0 or row >= 16:
                    continue
                for sx in range(3):
                    x = px + (sx + 0.5) / 3.0
                    # italic shear: shift x right as we go up from baseline
                    xx = x + shear * (baseline - y)
                    col = int(xx / cell_x)
                    line = rows[row]
                    if 0 <= col < len(line) and line[col] == '#':
                        cov += 1
            mask[py * pw + px] = cov
    m = (pw, ph, bytes(mask))
    _MASK_CACHE[key] = m
    return m

def text_width(text, size, tracking=0.0, hsqueeze=1.0):
    w = 0.0
    for ch in text:
        w += _advance_px(ch, size) * hsqueeze + tracking * size
    return w - (tracking * size if text else 0.0)

def draw_text(cv, x, y, text, size, color, italic=False, tracking=0.0,
              align='left', hsqueeze=1.0):
    """Draw text with top-left origin (x, y); size = cap-height px approx."""
    if not text:
        return x
    total = text_width(text, size, tracking, hsqueeze)
    if align == 'center':
        x = x - total / 2.0
    elif align == 'right':
        x = x - total
    cx = x
    for ch in text:
        if ch != ' ':
            pw, ph, mask = _glyph_mask(ch, size, italic, hsqueeze)
            ox = int(round(cx))
            oy = int(round(y))
            for py in range(ph):
                row = py * pw
                for px in range(pw):
                    cov = mask[row + px]
                    if cov:
                        cv.blend(ox + px, oy + py, color, cov)
        cx += _advance_px(ch, size) * hsqueeze + tracking * size
    return cx

def draw_text_fit(cv, x, y, w, text, size, color, italic=False,
                  tracking=0.0, min_size=None, align='left', hsqueeze=1.0):
    """Draw on one line; shrink down to min_size if it does not fit."""
    s = size
    while s > (min_size if min_size is not None else size) and \
            text_width(text, s, tracking, hsqueeze) > w:
        s -= 1
    draw_text(cv, x, y, text, s, color, italic, tracking, align, hsqueeze)
    return s

def wrap_text(text, size, max_w, tracking=0.0, hsqueeze=1.0):
    words = text.split(' ')
    lines = []
    cur = ''
    for wd in words:
        trial = wd if not cur else cur + ' ' + wd
        if text_width(trial, size, tracking, hsqueeze) <= max_w or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = wd
    if cur:
        lines.append(cur)
    return lines

def draw_para(cv, x, y, text, size, max_w, color, leading=None,
              max_lines=None, italic=False, tracking=0.0, hsqueeze=1.0):
    lines = wrap_text(text, size, max_w, tracking, hsqueeze)
    if max_lines is not None:
        lines = lines[:max_lines]
    ld = leading if leading is not None else int(size * 1.22)
    for i, ln in enumerate(lines):
        draw_text(cv, x, y + i * ld, ln, size, color, italic, tracking,
                  hsqueeze=hsqueeze)
    return y + len(lines) * ld

# ------------------------------------------------------------ font self-test --
def font_measurements(size=60):
    """Measure stem ratios on rendered glyphs: returns dict of findings."""
    out = {}
    # vertical stem of 'H': middle row of glyph, run length on the left stem
    pw, ph, mask = _glyph_mask('H', size)
    cell = size / 16.0
    mid = int(3.5 * cell)  # row 3: inside the stems, clear of the crossbar
    row = mask[mid * pw:(mid + 1) * pw]
    runs = []
    n = 0
    for v in row:
        if v >= 5:
            n += 1
        elif n:
            runs.append(n)
            n = 0
    if n:
        runs.append(n)
    out['H_vert_px'] = runs[0] if runs else 0
    # horizontal bar of 'H': middle column, vertical run length
    col = int(6 * cell)
    colvals = [mask[py * pw + col] >= 5 for py in range(ph)]
    n = 0
    best = 0
    for v in colvals:
        if v:
            n += 1
            best = max(best, n)
        else:
            n = 0
    out['H_horiz_px'] = best
    if out['H_horiz_px']:
        out['ratio'] = round(out['H_vert_px'] / out['H_horiz_px'], 2)
    # counter of 'o': hole width vs glyph width
    pw, ph, mask = _glyph_mask('o', size)
    mid = int(10 * cell)
    row = mask[mid * pw:(mid + 1) * pw]
    ink = [i for i, v in enumerate(row) if v >= 5]
    if ink:
        lo, hi = min(ink), max(ink)
        hole = 0
        inside = False
        for i in range(lo, hi + 1):
            if row[i] < 5:
                hole += 1
        out['o_counter_pct'] = round(100.0 * hole / max(1, hi - lo + 1))
    return out

