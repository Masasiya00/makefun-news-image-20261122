# ------------------------------------------------------------- PNG encoder --
def _chunk(kind, data):
    out = struct.pack(">I", len(data)) + kind + data
    out += struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
    return out

def _paeth(a, b, c):
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    if pb <= pc:
        return b
    return c

def encode_png(rgb, w, h):
    """rgb: bytearray of w*h*3. Returns PNG bytes (deterministic)."""
    raw = bytearray()
    prev = bytearray(w * 3)
    for y in range(h):
        row = bytes(rgb[y * w * 3:(y + 1) * w * 3])
        cands = []
        # filter 0 (None)
        cands.append((sum(abs(b - 128) for b in row), b"\x00" + row))
        # filter 1 (Sub)
        sub = bytearray(w * 3)
        for i in range(w * 3):
            left = row[i - 3] if i >= 3 else 0
            sub[i] = (row[i] - left) & 0xFF
        cands.append((sum(abs(b - 128) if b < 128 else abs(b - 256) for b in sub),
                      b"\x01" + bytes(sub)))
        # filter 2 (Up)
        up = bytes((row[i] - prev[i]) & 0xFF for i in range(w * 3))
        cands.append((sum(abs(b - 128) if b < 128 else abs(b - 256) for b in up),
                      b"\x02" + up))
        # filter 4 (Paeth)
        pa = bytearray(w * 3)
        for i in range(w * 3):
            a = row[i - 3] if i >= 3 else 0
            b = prev[i]
            c = prev[i - 3] if i >= 3 else 0
            pa[i] = (row[i] - _paeth(a, b, c)) & 0xFF
        cands.append((sum(abs(b - 128) if b < 128 else abs(b - 256) for b in pa),
                      b"\x04" + bytes(pa)))
        cands.sort(key=lambda t: t[0])
        raw += cands[0][1]
        prev = bytearray(row)
    ihdr = struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)
    return (b"\x89PNG\r\n\x1a\n" + _chunk(b"IHDR", ihdr)
            + _chunk(b"IDAT", zlib.compress(bytes(raw), 9))
            + _chunk(b"IEND", b""))

# ------------------------------------------------------------------ canvas --
def lerp(c1, c2, t):
    return tuple(int(round(c1[i] + (c2[i] - c1[i]) * t)) for i in range(3))

class Canvas:
    def __init__(self, w=W, h=H, bg=PAPER):
        self.w, self.h = w, h
        self.px = bytearray(w * h * 3)
        for y in range(h):
            base = y * w * 3
            for x in range(w):
                o = base + x * 3
                self.px[o] = bg[0]
                self.px[o + 1] = bg[1]
                self.px[o + 2] = bg[2]

    def set(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            o = (y * self.w + x) * 3
            self.px[o] = c[0]
            self.px[o + 1] = c[1]
            self.px[o + 2] = c[2]

    def blend(self, x, y, c, cov):
        """cov 0..9: coverage of source colour c over destination."""
        if cov <= 0 or not (0 <= x < self.w and 0 <= y < self.h):
            return
        o = (y * self.w + x) * 3
        if cov >= 9:
            self.px[o] = c[0]
            self.px[o + 1] = c[1]
            self.px[o + 2] = c[2]
            return
        k = 9 - cov
        self.px[o] = (c[0] * cov + self.px[o] * k) // 9
        self.px[o + 1] = (c[1] * cov + self.px[o + 1] * k) // 9
        self.px[o + 2] = (c[2] * cov + self.px[o + 2] * k) // 9

    def rect(self, x, y, w, h, c):
        x0 = max(0, int(x))
        y0 = max(0, int(y))
        x1 = min(self.w, int(x + w))
        y1 = min(self.h, int(y + h))
        if x1 <= x0 or y1 <= y0:
            return
        for yy in range(y0, y1):
            base = (yy * self.w + x0) * 3
            for xx in range(x0, x1):
                o = base + (xx - x0) * 3
                self.px[o] = c[0]
                self.px[o + 1] = c[1]
                self.px[o + 2] = c[2]

    def hline(self, x, y, w, c, t=1):
        self.rect(x, y, w, t, c)

    def vline(self, x, y, h, c, t=1):
        self.rect(x, y, t, h, c)

    def frame(self, x, y, w, h, c, t=1):
        self.rect(x, y, w, t, c)
        self.rect(x, y + h - t, w, t, c)
        self.rect(x, y, t, h, c)
        self.rect(x + w - t, y, t, h, c)

    def grad_rect(self, x, y, w, h, c1, c2, vertical=True):
        n = h if vertical else w
        if n <= 1:
            self.rect(x, y, w, h, c1)
            return
        for i in range(n):
            t = i / (n - 1)
            col = lerp(c1, c2, t)
            if vertical:
                self.rect(x, y + i, w, 1, col)
            else:
                self.rect(x + i, y, 1, h, col)

    def circle(self, cx, cy, r, c, fill=True):
        r = int(r)
        cx, cy = int(cx), int(cy)
        for yy in range(cy - r, cy + r + 1):
            dy = yy - cy
            dx = int((r * r - dy * dy) ** 0.5) if r * r - dy * dy >= 0 else 0
            if fill:
                self.rect(cx - dx, yy, dx * 2 + 1, 1, c)
            else:
                self.set(cx - dx, yy, c)
                self.set(cx + dx, yy, c)

    def ellipse(self, cx, cy, rx, ry, c):
        rx, ry = int(rx), int(ry)
        cx, cy = int(cx), int(cy)
        for yy in range(cy - ry, cy + ry + 1):
            dy = (yy - cy) / max(ry, 1)
            if abs(dy) > 1:
                continue
            dx = int(rx * (1 - dy * dy) ** 0.5)
            self.rect(cx - dx, yy, dx * 2 + 1, 1, c)

    def line(self, x0, y0, x1, y1, c, t=1):
        steps = max(abs(x1 - x0), abs(y1 - y0), 1)
        for i in range(steps + 1):
            tt = i / steps
            x = int(round(x0 + (x1 - x0) * tt))
            y = int(round(y0 + (y1 - y0) * tt))
            if t <= 1:
                self.set(x, y, c)
            else:
                self.circle(x, y, t // 2, c)

    def poly(self, pts, c):
        """Scanline fill of a simple polygon [(x,y), ...]."""
        if len(pts) < 3:
            return
        ys = [p[1] for p in pts]
        y0, y1 = int(min(ys)), int(max(ys))
        n = len(pts)
        for y in range(y0, y1 + 1):
            xs = []
            for i in range(n):
                x0, yy0 = pts[i]
                x1, yy1 = pts[(i + 1) % n]
                if (yy0 <= y < yy1) or (yy1 <= y < yy0):
                    if yy1 != yy0:
                        xs.append(x0 + (y - yy0) * (x1 - x0) / (yy1 - yy0))
            xs.sort()
            for k in range(0, len(xs) - 1, 2):
                self.rect(int(xs[k]), y, max(1, int(xs[k + 1]) - int(xs[k])), 1, c)

    def star(self, cx, cy, r, c):
        r = int(r)
        self.rect(cx - r, cy, r * 2 + 1, 1, c)
        self.rect(cx, cy - r, 1, r * 2 + 1, c)
        self.set(cx - r + 1, cy - r + 1, c)
        self.set(cx + r - 1, cy - r + 1, c)
        self.set(cx - r + 1, cy + r - 1, c)
        self.set(cx + r - 1, cy + r - 1, c)

