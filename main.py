def arc_top(cv, cx, cy, rx, ry, c):
    """Top half of an ellipse outline, drawn as short line segments."""
    import math
    n = 26
    prev = None
    for i in range(n + 1):
        a = math.pi + math.pi * i / n  # 180..360 deg = upper half
        px = int(cx + rx * math.cos(a))
        py = int(cy + ry * math.sin(a))
        if prev is not None:
            cv.line(prev[0], prev[1], px, py, c, 1)
        prev = (px, py)

